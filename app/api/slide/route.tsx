import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { ImageResponse } from "next/og";
import { themeById, sizeFor, SLIDE_W, SLIDE_H } from "@/lib/slides/design";

export const runtime = "nodejs";

/**
 * Inter, shipped with the app rather than fetched.
 *
 * Satori has no fonts of its own and will not synthesise a bold weight, so
 * without these every slide renders at a single light weight and the type
 * hierarchy that makes a deck look designed simply does not appear.
 * Fetching from Google at request time would work and would also mean a
 * cold start can fail to render a slide because someone else's CDN is
 * having a moment. Inter is OFL licensed; the licence ships beside it.
 *
 * Read once per process, not per request.
 */
let fontCache: { semibold: ArrayBuffer; extrabold: ArrayBuffer } | null = null;

async function fonts() {
  if (fontCache) return fontCache;
  const dir = join(process.cwd(), "assets", "fonts");
  const [semibold, extrabold] = await Promise.all([
    readFile(join(dir, "Inter-SemiBold.otf")),
    readFile(join(dir, "Inter-ExtraBold.otf")),
  ]);
  fontCache = {
    semibold: semibold.buffer.slice(semibold.byteOffset, semibold.byteOffset + semibold.byteLength) as ArrayBuffer,
    extrabold: extrabold.buffer.slice(extrabold.byteOffset, extrabold.byteOffset + extrabold.byteLength) as ArrayBuffer,
  };
  return fontCache;
}

/**
 * The team logo, inlined as a data URI.
 *
 * Satori cannot fetch a URL, and pointing it at our own route would mean a
 * slide render waiting on a second request to ourselves. The file is
 * 190KB, read once per process and reused.
 *
 * A missing logo returns null rather than throwing: a slide without the
 * mark is still a usable slide, and a whole carousel failing because one
 * file moved would not be.
 */
let logoCache: string | null | undefined;

async function logo(): Promise<string | null> {
  if (logoCache !== undefined) return logoCache;
  try {
    const file = await readFile(join(process.cwd(), "assets", "brand", "riseup-logo.png"));
    logoCache = `data:image/png;base64,${file.toString("base64")}`;
  } catch {
    logoCache = null;
  }
  return logoCache;
}

/**
 * One carousel slide, as a PNG.
 *
 * Rendered rather than generated by an image model, on purpose. A slide is
 * mostly words, and image models misspell words. This way the text is
 * exactly what was written, at Instagram's full portrait size, and it
 * costs nothing per image.
 *
 * The layout carries the deck: a hook slide that looks like a cover, body
 * slides that look like a series, and a footer that is the same on every
 * one. That repetition is what makes eight images read as one carousel.
 */
export async function GET(request: Request) {
  const [loaded, logoSrc] = await Promise.all([fonts(), logo()]);
  const { searchParams } = new URL(request.url);
  const text = (searchParams.get("text") ?? "").slice(0, 400);
  const index = Number(searchParams.get("i") ?? "1");
  const total = Number(searchParams.get("n") ?? "1");
  const handle = (searchParams.get("handle") ?? "").slice(0, 40);
  const t = themeById(searchParams.get("theme"));
  const isHook = index === 1;
  const isLast = total > 1 && index === total;
  const size = sizeFor(text, isHook ? "hook" : "body");

  return new ImageResponse(
    (
      <div
        style={{
          width: "100%",
          height: "100%",
          display: "flex",
          flexDirection: "column",
          background: t.bg,
          position: "relative",
          fontFamily: "Inter",
        }}
      >
        {/* A soft wash of the accent, anchored to a different corner on the
            cover than on the body slides. Enough to feel designed, far
            enough from the text to never fight it for attention. */}
        <div
          style={{
            position: "absolute",
            width: 980,
            height: 980,
            borderRadius: 980,
            left: isHook ? -260 : SLIDE_W - 620,
            top: isHook ? SLIDE_H - 760 : -420,
            background: t.accent,
            opacity: isHook ? 0.1 : 0.06,
            filter: "blur(170px)",
            display: "flex",
          }}
        />

        {/* A single rule across the top, filling as the deck progresses.
            A progress bar people read without noticing they read it. The
            gold hairline under it is the one place gold appears at full
            width, mirroring how the logo uses it. */}
        {total > 1 && (
          <div style={{ display: "flex", flexDirection: "column", width: "100%" }}>
            <div style={{ display: "flex", width: "100%", height: 8 }}>
              <div
                style={{
                  display: "flex",
                  width: `${Math.round((index / total) * 100)}%`,
                  background: t.accent,
                }}
              />
            </div>
            <div style={{ display: "flex", width: "100%", height: 2, background: t.trim, opacity: 0.5 }} />
          </div>
        )}

        <div
          style={{
            display: "flex",
            flexDirection: "column",
            flex: 1,
            padding: "96px 88px 76px 88px",
            justifyContent: isHook ? "flex-end" : "center",
          }}
        >
          {!isHook && (
            <div style={{ display: "flex", alignItems: "center", marginBottom: 44 }}>
              <div
                style={{
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  width: 84,
                  height: 84,
                  borderRadius: 84,
                  background: t.accent,
                  color: t.onAccent,
                  fontSize: 42,
                  fontWeight: 700,
                }}
              >
                {index}
              </div>
              {isLast && (
                <div
                  style={{
                    display: "flex",
                    marginLeft: 24,
                    fontSize: 26,
                    letterSpacing: 4,
                    textTransform: "uppercase",
                    color: t.dim,
                  }}
                >
                  Last one
                </div>
              )}
            </div>
          )}

          <div
            style={{
              display: "flex",
              fontSize: size,
              lineHeight: 1.18,
              fontWeight: isHook ? 800 : 600,
              color: t.ink,
              letterSpacing: isHook ? -2 : -1,
              // Hooks are a statement and sit tight to the left margin.
              // Body slides breathe a little more.
              maxWidth: isHook ? 900 : 880,
            }}
          >
            {text}
          </div>

          {isHook && (
            <div
              style={{
                display: "flex",
                width: 160,
                height: 10,
                background: t.accent,
                marginTop: 52,
              }}
            />
          )}

          {(isHook || isLast) && t.logo && logoSrc && (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={logoSrc}
              width={520}
              alt=""
              style={{ marginTop: isHook ? 64 : 56 }}
            />
          )}
        </div>

        <div
          style={{
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
            padding: "0 88px 72px 88px",
          }}
        >
          <div style={{ display: "flex", fontSize: 28, color: t.dim, letterSpacing: 1 }}>
            {handle ? `@${handle.replace(/^@/, "")}` : ""}
          </div>
          <div style={{ display: "flex", fontSize: 28, color: t.dim, letterSpacing: 2 }}>
            {total > 1 ? `${index} / ${total}` : ""}
          </div>
        </div>
      </div>
    ),
    {
      width: SLIDE_W,
      height: SLIDE_H,
      fonts: [
        { name: "Inter", data: loaded.semibold, weight: 600, style: "normal" },
        { name: "Inter", data: loaded.extrabold, weight: 800, style: "normal" },
      ],
      headers: {
        // Same text always renders the same picture, so let the browser
        // keep it rather than re-rendering on every preview.
        "Cache-Control": "public, max-age=31536000, immutable",
      },
    },
  );
}
